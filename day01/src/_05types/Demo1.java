package _05types;

/*
## 什么是基本数据类型和引用数据类型

### 基本数据类型（Primitive Types）

Java 中预定义的 **8 种**最基础的数据类型，它们直接表示一个具体的值。

| 类型 | 关键字 | 大小 | 示例 |
|---|---|---|---|
| 整型 | `byte` | 1 字节 | `127` |
| 整型 | `short` | 2 字节 | `32000` |
| 整型 | `int` | 4 字节 | `100` |
| 整型 | `long` | 8 字节 | `100L` |
| 浮点型 | `float` | 4 字节 | `3.14f` |
| 浮点型 | `double` | 8 字节 | `3.14` |
| 字符型 | `char` | 2 字节 | `'A'` |
| 布尔型 | `boolean` | 未明确定义 | `true` |

**特点：** 变量名**直接对应**数值本身，创建时不需要 `new`。

```java
int age = 25;          // age 就是 25 本身
char grade = 'A';      // grade 就是 'A' 本身
```
---

### 引用数据类型（Reference Types）

除了 8 种基本类型外，**所有其他类型**都是引用数据类型，包括：

- **类（Class）：** `String`、`Person`、`Scanner` 等
- **接口（Interface）：** `List`、`Runnable` 等
- **数组（Array）：** `int[]`、`String[]` 等
- **枚举（Enum）：** 自定义枚举类型

**特点：** 变量名保存的是对象的**内存地址**，需要通过 `new` 关键字创建对象。

```java
String name = new String("张三");   // name 存的是"张三"这个对象在堆里的地址
int[] arr = new int[3];             // arr 存的是数组对象在堆里的地址
Person p = new Person();            // p 存的是 Person 对象的地址
```

---

## 为什么要有这种区分？

这是 Java **性能与面向对象设计之间的权衡**，核心原因有三个：

### 1. 性能优化 —— 基本类型更快

堆内存（对象）的创建、访问和回收成本远高于栈内存。对于**高频使用的小数据**（如循环计数器的 `int i`），如果也用对象创建，性能会大幅下降。

```java
// 如果 int 也是对象：
Integer i = new Integer(0);  // 堆分配、GC回收 → 慢
i = i + 1;                   // 拆箱+装箱 → 更慢

// 但实际 int 是这样的：
int i = 0;   // 栈直接存储 → 极快
i++;
```

### 2. 内存效率 —— 基本类型更省空间

| 类型 | 基本类型（栈） | 包装类对象（堆） |
|---|---|---|
| `int` | **4 字节** | 16~24 字节（对象头+数据+对齐） |
| `boolean` | **1 字节** | 16~24 字节 |

对象在堆中除了数据本身，还要额外存储**对象头**（标记字、类指针等），占用更多内存。

### 3. 语义区分 —— 明确值的含义

- **基本类型** = 没名字的"值本身"（好比「数字 5」）
- **引用类型** = 有身份的对象（好比「名叫张三的人」）

```java
int a = 5;
int b = a;   // a 和 b 完全独立，修改 b 不影响 a

String s1 = new String("Hi");
String s2 = s1;   // s1 和 s2 指向同一个对象，修改会影响另一个
```

这种区分让程序员能明确知道 **赋值是"值拷贝"还是"地址拷贝"**，避免混淆。

---

### 一句话总结

| | 基本类型 | 引用类型 |
|---|---|---|
| 本质 | 直接存"值" | 存"对象的地址" |
| 存储 | 栈 | 栈存地址，堆存数据 |
| 性能 | 快、省内存 | 慢、占内存 |
| 典型场景 | 数字计算、循环控制 | 复杂对象、集合、字符串 |

**Java 的设计哲学就是：**
> 把常见的"小数据"做成基本类型追求性能，把"大数据/复杂结构"做成引用类型追求面向对象的灵活性。两者互补，各司其职。
-----------------------------------------------------

## Java 基本数据类型 vs 引用数据类型的内存存储

### 1. 基本数据类型（Primitive Types）

**包含：** `byte`, `short`, `int`, `long`, `float`, `double`, `char`, `boolean`

**存储过程：**

- **存储位置：栈（Stack）**
- 变量的值**直接**存储在栈内存中
- 声明时直接分配固定大小的内存空间（大小由类型决定，如 `int` 占 4 字节）
- 栈内存由系统自动管理，方法执行完毕即释放

```
栈内存：
┌─────────────┐
│ int a = 10  │  ← 直接存储值 10
├─────────────┤
│ double b=3.14│  ← 直接存储值 3.14
└─────────────┘
```

**特点：** 访问速度快、生命周期由作用域控制、赋值是**值拷贝**

---

### 2. 引用数据类型（Reference Types）

**包含：** 类（`class`）、接口（`interface`）、数组（`[]`）、枚举（`enum`）

**存储过程（分两步）：**

1. **栈（Stack）：** 存储引用变量（即对象的**内存地址**，类似指针）
2. **堆（Heap）：** 存储对象的**实际数据**

```
栈内存：                         堆内存：
┌─────────────────┐             ┌──────────────────┐
│ Person p = 0x123 │──地址指向──→│  name = "张三"    │
└─────────────────┘             │  age = 25        │
                                │  ...             │
                                └──────────────────┘
```

**赋值时的区别：** 引用类型赋值传递的是**地址**，多个引用可指向同一对象

```java
Person p1 = new Person("张三", 25);
Person p2 = p1;          // p2 和 p1 指向同一个堆对象
p2.setName("李四");       // p1.getName() 也会变成 "李四"
```

---

### 关键对比总结

| 对比维度 | 基本数据类型 | 引用数据类型 |
|---|---|---|
| 栈存储 | 存**值本身** | 存**地址**（指针） |
| 堆存储 | 无 | 存**实际对象数据** |
| 赋值行为 | 值拷贝（独立） | 地址拷贝（共享） |
| == 比较 | 比较值 | 比较地址（是否同一对象） |
| 默认值 | 有固定默认值（如 0, false） | `null` |
| 垃圾回收 | 方法结束自动释放 | GC 回收无引用的堆对象 |

**一句话总结：** 基本数据类型 **"人就在栈里"**，引用数据类型 **"栈里只是门牌号，人住在堆里"**。
*/
public class Demo1 {
    public static void main(String[] args) {
        // 整型
        byte a = 100;
        short b = 1000;
        int c = 10000;
        long d = 10000000000L;

        // 浮点类型
        float e = 0.1f; // 单精度
        double f = 0.1; // 双精度

        // 字符
        char g = 'e';
        // 字符串它是引用数据类型，后面聊
        String h = "fff";

        // 布尔
        boolean flag1 = true;
        boolean flag2 = false;
    }
}
