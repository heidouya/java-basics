package _07operators;

/*
    关系运算符：
    >：大于
    <：小于
    >=：大于等于
    <=：小于等于
    ==：等于
    !=：不等于
*/
public class Demo3 {
    public static void main(String[] args) {
        int a = 1, b = 2;
        System.out.println(a > b); // false
        System.out.println(a < b); // true
        System.out.println(a >= b);// false
        System.out.println(a <= b); // true
        System.out.println(a == b); // false
        System.out.println(a != b);// true
    }
}
