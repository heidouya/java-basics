package _06operators;

/*
    赋值运算符：
    +=：加等于
    -=：减等于
    *=：乘等于
    /=：除等于
*/
public class Demo2 {
    public static void main(String[] args) {
        int a = 11, b = 2;
        // 复合赋值运算符
        a += b; // a = a + b;
        a -= b; // a = a - b;
        a *= b; // a = a * b;
        a /= b; // a = a / b;
    }
}
