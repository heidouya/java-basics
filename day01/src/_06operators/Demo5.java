package _06operators;

/*
    位运算符：
    &：与
    |：或
    !：非
    ^：异或
    ~：取反
    <<：左移
    >>：右移
    >>>：无符号右移
    原码：
        规则：最高位是「符号位」（0 = 正，1 = 负），剩下位存数值的二进制。

        例子（以 8 位二进制为例）：
        5 的原码 → 0000 0101
        -5 的原码 → 1000 0101
        直接用原码算减法（5 - 5 = 0）会出错 → 00000101 + 10000101 = 10001010（=-10≠0），所以原码只用于「直观表示」，不用于计算。
    反码：
        规则：正数：反码 = 原码；负数：反码 = 原码的「符号位不变，数值位取反（0 变 1，1 变 0）」。

        例子（8 位）：
        5 的反码 → 0000 0101
        -5 的反码 → 1111 1010
        算减法仍有小缺陷（0 有两种表示：+0=00000000，-0=11111111），最终被补码取代。
    补码：
        规则：正数：补码 = 原码 = 反码；负数：补码 = 反码 + 1（解决了 - 0 的问题）。

        例子（8 位）：
        5 的补码 → 0000 0101
        -5 的补码 → 1111 1010 + 1 = 1111 1011
        00000101 + 11111011 = 1 00000000 → 舍弃进位，结果 = 0（正确）

    原码、反码、补码：为了用二进制统一处理正负数的加减运算。
*/
public class Demo5 {
    public static void main(String[] args) {
        // 按位与计算规则：二进制对应位都为 1 才是 1，否则为 0
        /*
            0010
           &
            0001
           =
            0000 -> 0
        */
        System.out.println(2 & 1); // 0

        // 按位或计算规则：二进制对应位有一个 1 就是 1，都为 0 才是 0
        /*
            0010
           |
            0001
           =
            0011 -> 3
        */
        System.out.println(2 | 1); // 3

        // 异或计算规则：二进制对应位相同为 0，不同为 1
        /*
            0010
           ^
            0001
           =
            0011 -> 3
        */
        System.out.println(2 ^ 1); // 3

        // 取反计算规则：二进制位 0 变 1，1 变 0（Java 中是补码取反，结果为 -(n+1)）
        // 0010 ->
        System.out.println(~2); // -3

        // 左移计算规则：二进制位整体左移 N 位，右边补 0 → 等价于「数值 × 2 的 N 次方」（效率远高于乘法）
        // 简记：左移 = 乘以 2^N
        // 0010 << 0100 -> 4
        System.out.println(2 << 5); // 0010 << 5 -> 0100 0000 -> 64

        // 右移计算规则：二进制位整体右移 N 位，左边补「符号位」（正数补 0，负数补 1）→ 等价于「数值 ÷ 2 的 N 次方（向下取整）」
        // 简记：正数右移 = 整除 2^N，负数右移仍为负数（向下取整）
        System.out.println(2 >> 1); // 0010 >> 1 -> 0001 -> 1
        System.out.println(-8 >> 2); // 1000 >> 2 -> 0010 -> -2

        // 无符号右移规则：二进制位整体右移 N 位，左边一律补 0 → 负数会变成大正数（忽略符号位）
        // 简记：不管正负，右移后都是非负数
        System.out.println(2 >>> 1); // 0010 >>> 1 -> 0001 -> 1

        /*
        正数 2 的原码（32 位）：0000 0000 0000 0000 0000 0000 0000 0010
        负数 2 的原码（32 位）：1000 0000 0000 0000 0000 0000 0000 0010
        负数 2 的反码（32 位）：1111 1111 1111 1111 1111 1111 1111 1101
        负数 2 的补码（32 位）：1111 1111 1111 1111 1111 1111 1111 1110
        负数 2 的补码右移1位后：0111 1111 1111 1111 1111 1111 1111 1111
        将结果转化位十进制后得：2^31 - 1 = 2147483647
        */
        System.out.println(-2 >>> 1); // 2147483647
    }
}
