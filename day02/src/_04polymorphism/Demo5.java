package _04polymorphism;

/*
    抽象类：抽象类是使用abstract关键字修饰的类，它不能被实例化，主要用于定义子类的通用模板，可以包含抽象方法和具体方法。
    比如前面的例子中可以将“鸿蒙设备”定义为一个抽象类 —— 定义所有设备都必须有powerOn()方法，但不同设备（手机 / 平板 / 手表）的开机逻辑不同，所以抽象类只声明方法，不写具体实现，让子类去补全。

    抽象类 vs 普通类：
    ------------------------------------------------
    特性	                抽象类	            普通类
    ------------------------------------------------
    实例化	            不能new	            可以new
    ------------------------------------------------
    抽象方法	            可以包含	            不能包含
    ------------------------------------------------
    继承	                必须被继承	        可选被继承
    ------------------------------------------------
    构造方法	            可以有	            可以有
    ------------------------------------------------

    核心规则：
    1. 关键字：类用abstract class修饰，抽象方法用abstract修饰（无方法体，以;结尾）；
    2. 不能实例化：抽象类无法用new创建对象（比如new HarmonyDevice()会编译报错），只能被子类继承；
    3. 混合特性：可包含「抽象方法（无实现）+ 普通方法（有实现）+ 属性」，子类继承后必须实现所有抽象方法（除非子类也是抽象类）。

    核心使用场景：
    1. 封装通用逻辑，强制子类实现差异化逻辑：比如鸿蒙开发中，定义BaseAbility抽象类，封装页面初始化的通用逻辑（普通方法），声明initUI()抽象方法，强制每个页面子类实现自己的 UI 布局；
    2. 作为多态的父类模板：抽象类不能实例化，但可作为父类引用，指向子类对象，实现多态（比普通父类更严格，确保子类必实现核心方法）；
    3. 避免重复代码：抽象类的普通方法可复用（如设备 ID 展示），抽象方法强制子类定制化（如不同设备的开机逻辑）。

    注意：
    1. ❌ 抽象类不能实例化，但可定义构造函数（供子类初始化父类属性）；
    2. ❌ 抽象方法不能是private、static、final
    3. ❌ 抽象类中可无抽象方法（但失去核心意义，一般用于禁止实例化）；
    4. ✅ 子类若不实现抽象方法，必须把自己也声明为抽象类；
    5. ✅ 可以包含各种成员：属性、方法、静态成员
    5. ✅ 抽象类 vs 接口：抽象类可有普通方法 / 属性，接口（Java8+）仅默认方法 / 静态方法，抽象类适合 “部分复用、部分定制”，接口适合 “全定制”。

    抽象类与接口的比较：
    ----------------------------------------------------------------------
    比较项	            抽象类	                    接口
    ----------------------------------------------------------------------
    关键字	            abstract class	            interface
    ----------------------------------------------------------------------
    继承/实现	        单继承	                    多实现
    ----------------------------------------------------------------------
    构造方法	            可以有	                    不能有
    ----------------------------------------------------------------------
    属性	                各种修饰符	                默认public static final
    ----------------------------------------------------------------------
    方法	                抽象、具体、静态、final	    抽象、默认、静态
    ----------------------------------------------------------------------
    访问修饰符	        所有	                        默认public
    ----------------------------------------------------------------------

    总结
    1. 抽象类核心：abstract修饰，不能实例化，可包含抽象方法（强制子类实现）和普通方法（复用）；
    2. 核心规则：子类必须实现所有抽象方法，否则子类也需声明为抽象类；
    3. 实用价值：封装通用逻辑、强制子类实现差异化功能，是鸿蒙 / Java 开发中标准化子类行为的核心手段。
*/
public class Demo5 {
    // 3. 使用抽象类（通过子类实例化）
    public static void main(String[] args) {
        // 多态：抽象类引用指向子类对象
        HarmonyDevice2 phone = new HarmonyPhone2();

        phone.deviceId = "HM1001";

        phone.powerOn(); // 执行子类实现的开机逻辑
        phone.showDeviceId(); // 复用抽象类的普通方法

        // 下面代码用来解释为什么抽象类的抽象方法不能省略
        HarmonyDevice2 watch = new HarmonyWatch();
        watch.deviceId = "HM1002";

        HarmonyDevice2 pad = new HarmonyPad2();
        pad.deviceId = "HM1003";

        powerOn(watch);
        powerOn(pad);
    }

    public static void powerOn(HarmonyDevice2 device) {
        // 如果抽象类中的抽象方法省略不写，这里就找不到对应的方法，会报错
        device.powerOn();
    }
}

// 1. 抽象类：定义模板，包含抽象方法和普通方法
abstract class HarmonyDevice2 {
    protected String deviceId;

    // 抽象方法：只声明，无实现（子类必须重写）
    // 这个方法可以省略吗？答：不能，为了实现多态
    public abstract void powerOn();

    // 普通方法：有实现，子类可直接复用
    public void showDeviceId() {
        System.out.println("设备ID：" + deviceId);
    }
}

// 2. 子类：必须实现抽象类的所有抽象方法
class HarmonyPhone2 extends HarmonyDevice2 {
    @Override
    public void powerOn() {
        System.out.println(deviceId + "：手机开机，连接蓝牙");
    }
}

class HarmonyWatch extends HarmonyDevice2 {
    @Override
    public void powerOn() {
        System.out.println(deviceId + "：手表开机");
    }
}

class HarmonyPad2 extends HarmonyDevice2 {
    @Override
    public void powerOn() {
        System.out.println(deviceId + "：Pad开机");
    }
}
