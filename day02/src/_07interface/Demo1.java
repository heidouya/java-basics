package _07interface;

/*
接口是 Java 中一种特殊的抽象类型，它是方法的集合、规范的定义，只规定能做什么，不规定具体怎么做，是面向对象编程中解耦、多态的核心机制。简单来说，接口就是定义一套规则，让不同对象都能按照这套规则去执行，但具体怎么做，由各自决定。

核心特点：
1. 本质是规范 / 契约
接口定义一组公共方法签名，实现类必须重写所有方法（默认方法除外），遵守这个契约。
2. 不能实例化
接口没有构造方法，不能直接new对象，只能被类实现（implements）。
3. 支持多实现
一个类可以实现多个接口（弥补 Java 单继承的局限）；一个接口可以继承多个接口。
4. 成员特性（Java 8+）
4.1 常量：默认 public static final（可省略不写）
4.2 抽象方法：默认 public abstract（可省略不写）
4.3 默认方法：default 修饰，有方法体，实现类可直接用 / 重写
4.4 静态方法：static 修饰，接口直接调用
4.5 私有方法：Java 9+，供内部默认 / 静态方法复用

接口 vs. 抽象类：
1. 抽象类 表达 “是什么”（is-a），如 Dog is an Animal，适合共享通用代码。
2. 接口 表达 “能做什么”（has-a / like-a），如 Dog can Run，适合定义跨类别的能力。

接口和抽象类的区别：
特性	                        接口	                     抽象类
继承 / 实现	            类用implements实现	    类用extends继承
数量限制	                一个类可实现多个接口	    一个类只能继承一个父类
构造方法	                    无	                        有
成员变量	                只能是常量	            可定义普通变量

核心作用：
1. 实现多态，统一调用规范
2. 解耦代码，分离定义和实现
3. 打破单继承限制，让类具备多种能力
*/
public class Demo1 {
    public static void main(String[] args) {
        // 多态：接口引用指向实现类对象
        Dog dog = new Dog();
        dog.run();
        dog.eat();
        dog.breathe(); // 调用默认方法
    }
}
