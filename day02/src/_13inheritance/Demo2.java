package _13inheritance;

/*
    super：super是Java中的一个引用变量，用于直接引用父类的成员（属性、方法、构造函数）。当子类覆盖了父类的成员时，可以使用super来访问父类被隐藏的成员。

    1. 调用父类构造函数：super()，必须放在第一行。
    2. 调用父类有参构造函数：super(参数1, 参数2...)，super必须放在第一行。
    3. 访问父类非私有属性：super.想访问的属性名
    4. 访问父类非私有方法：super.想访问的方法名()

    super的主要作用：
    1. 访问父类被隐藏的属性：当子类定义了同名属性时
    2. 调用父类被重写的方法：在扩展父类方法的同时复用父类逻辑
    3. 调用父类构造函数：确保父类部分正确初始化
    5. 解决命名冲突：明确指定要访问的是父类成员

    使用注意事项：
    1. 只能在非静态方法中使用
    2. 调用构造函数时必须放在第一行
    3. 不能访问父类的私有成员
    4. 不能连续使用（如super.super）

    super与this的对比：
    特性	            super               this
    引用对象	        父类对象	            当前对象
    访问属性	        父类属性	            当前类属性
    调用方法	        父类方法	            当前类方法
    调用构造	        父类构造	            当前类构造
    使用位置	        必须在第一行	        必须在第一行
    静态上下文	    不能使用	            不能使用
*/
